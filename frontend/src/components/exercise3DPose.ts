export type CameraPreset = 'studio' | 'side' | 'front';

export type Vec3 = [number, number, number];

export interface Pose3D {
  /** Posición mundial de la pelvis (en metros aprox.; suelo en y = 0) */
  pelvisPos: Vec3;
  /** Rotación de la pelvis en radianes [rx, ry, rz] (controla inclinación global del cuerpo) */
  pelvisRot: Vec3;
  /** Inclinación relativa columna / torso [rx, ry, rz] */
  spineRot: Vec3;
  /** Inclinación de cabeza [rx, ry, rz] */
  headRot: Vec3;
  /** Hombro izquierdo y derecho [rx, ry, rz] */
  leftShoulder: Vec3;
  rightShoulder: Vec3;
  /** Flexión de codo (valores <= 0 doblan el antebrazo) */
  leftElbow: number;
  rightElbow: number;
  /** Cadera izquierda y derecha [rx, ry, rz] */
  leftHip: Vec3;
  rightHip: Vec3;
  /** Flexión de rodilla (valores >= 0 doblan la pantorrilla atrás) */
  leftKnee: number;
  rightKnee: number;
  /** Flexión dorsal/plantar del tobillo (valores > 0 apuntan puntera abajo) */
  leftAnkle: number;
  rightAnkle: number;
}

export interface Exercise3DSpec {
  id: string;
  environment: 'floor' | 'wall-front' | 'wall-back' | 'elevated-bench';
  defaultCamera: CameraPreset;
  startPose: Pose3D;
  peakPose: Pose3D;
}

const lerp = (a: number, b: number, t: number) => a + (b - a) * t;

const lerpVec3 = (a: Vec3, b: Vec3, t: number): Vec3 => [
  lerp(a[0], b[0], t),
  lerp(a[1], b[1], t),
  lerp(a[2], b[2], t),
];

export function interpolatePose3D(a: Pose3D, b: Pose3D, t: number): Pose3D {
  return {
    pelvisPos: lerpVec3(a.pelvisPos, b.pelvisPos, t),
    pelvisRot: lerpVec3(a.pelvisRot, b.pelvisRot, t),
    spineRot: lerpVec3(a.spineRot, b.spineRot, t),
    headRot: lerpVec3(a.headRot, b.headRot, t),
    leftShoulder: lerpVec3(a.leftShoulder, b.leftShoulder, t),
    rightShoulder: lerpVec3(a.rightShoulder, b.rightShoulder, t),
    leftElbow: lerp(a.leftElbow, b.leftElbow, t),
    rightElbow: lerp(a.rightElbow, b.rightElbow, t),
    leftHip: lerpVec3(a.leftHip, b.leftHip, t),
    rightHip: lerpVec3(a.rightHip, b.rightHip, t),
    leftKnee: lerp(a.leftKnee, b.leftKnee, t),
    rightKnee: lerp(a.rightKnee, b.rightKnee, t),
    leftAnkle: lerp(a.leftAnkle, b.leftAnkle, t),
    rightAnkle: lerp(a.rightAnkle, b.rightAnkle, t),
  };
}

